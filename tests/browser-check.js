// Run with: playwright-cli -s=lennytype run-code --filename=tests/browser-check.js
// Start the local API and a static build at http://localhost:4173/lennytype/ first.
async page => {
  const assert = (value,message) => { if (!value) throw new Error(message); };
  await page.goto('http://localhost:4173/lennytype/');
  await page.waitForFunction(() => dictionary.length > 0);
  assert(await page.evaluate(() => state === 'home' && session === null), 'Home automatically joined a room');
  assert(await page.locator('#home button').count() === 2, 'Homepage needs two room buttons');
  assert(await page.locator('footer,.mode-strip,.shortcuts').count() === 0, 'Removed UI is still present');
  await page.locator('#createRoom').click();
  await page.waitForFunction(() => session && state === 'lobby');
  const code = await page.locator('#roomCode').textContent();
  assert(/^[A-Z0-9]{6}$/.test(code), 'Visible room code missing');
  assert(await page.locator('#typingArea').isHidden(), 'Waiting room exposes race words');
  assert(await page.locator('.caret').count() === 0, 'Waiting room has cursors');
  const context = await page.context().browser().newContext();
  const guest = await context.newPage();
  await guest.goto('http://localhost:4173/lennytype/');
  await guest.locator('#browseRooms').click();
  await guest.locator(`[data-room="${code}"]`).click();
  await guest.waitForFunction(() => session && state === 'lobby');
  assert(await guest.locator('#typingArea').isHidden(), 'Joined lobby exposes words');
  await page.waitForFunction(() => players.length === 2);
  await page.locator('#startButton').click();
  await Promise.all([page.waitForFunction(() => state === 'racing'),guest.waitForFunction(() => state === 'racing')]);
  const initial = await page.evaluate(() => ({start:startAt,words:words.slice(0,20).join(' ')}));
  assert(JSON.stringify(initial) === JSON.stringify(await guest.evaluate(() => ({start:startAt,words:words.slice(0,20).join(' ')}))), 'Shared clock or words differ');
  await page.locator('#typingArea').hover();
  const carets = await page.evaluate(() => {
    const area = $('typingArea').getBoundingClientRect();
    const own = document.querySelector('[data-caret="local"]').getBoundingClientRect();
    return {outsideClip:$('carets').parentElement === $('typingArea'),intact:own.top >= area.top && own.bottom <= area.bottom,colors:[...$('carets').children].map(el => el.style.getPropertyValue('--cursor'))};
  });
  assert(carets.outsideClip && carets.intact, 'First-line caret remains clipped');
  assert(new Set(carets.colors).size === 2, 'Player cursor colors collide');
  await page.keyboard.type(await page.evaluate(() => words.slice(0,30).join(' ') + ' '),{delay:3});
  await guest.waitForFunction(() => players.some(p => p.id !== session.id && p.position > 50));
  assert(await page.evaluate(() => scrollY > 0), 'Typing did not scroll the words');
  await page.keyboard.type('!');
  assert(await page.locator('.letter.incorrect,.letter.extra').count() > 0, 'Typo is not marked');
  await page.keyboard.press('Backspace');
  assert(await page.locator('.letter.incorrect,.letter.extra').count() === 0, 'Backspace did not correct the typo');
  await page.screenshot({path:'/tmp/lennytype-racing.png'});
  await page.locator('#leaveRoom').click();
  assert(await page.evaluate(() => state === 'home' && session === null), 'Cannot leave a running race');
  await guest.waitForFunction(() => players.length === 1 && room.host === session.id);
  assert(await guest.evaluate(() => startAt) === initial.start, 'Leaving restarted the shared race');
  await page.locator('#browseRooms').click();
  await page.locator(`[data-room="${code}"]`).click();
  await page.waitForFunction(() => state === 'racing');
  await guest.keyboard.type(await guest.evaluate(() => words.slice(0,7).join(' ') + ' '),{delay:4});
  await Promise.all([page.waitForFunction(() => state === 'finished',{},{timeout:40000}),guest.waitForFunction(() => state === 'finished',{},{timeout:40000})]);
  assert(await guest.locator('#results').isVisible(), 'Results missing');
  assert(await guest.locator('#resultWpm').textContent() !== '0', 'Typed words were not counted');
  await guest.keyboard.press('Enter');
  await page.waitForFunction(() => state === 'countdown');
  assert(await page.evaluate(() => position === 0 && correct === 0), 'Rematch did not reset progress');
  await page.locator('#leaveRoom').click();
  await guest.locator('#leaveRoom').click();
  await page.locator('#browseRooms').click();
  await page.waitForFunction(code => !document.querySelector(`[data-room="${code}"]`),code);
  await page.locator('#joinDialog .dialog-header button').click();
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), 'Mobile has horizontal overflow');
  await page.screenshot({path:'/tmp/lennytype-mobile.png'});
  await page.setViewportSize({width:1440,height:900});
  await page.screenshot({path:'/tmp/lennytype-home.png'});
  await context.close();
  return {passed:true,room:code,carets,checked:['empty home and lobby','room browser','shared timer and words','cursor clipping','typing and corrections','leave during race','host handoff','rejoin','30-second results','rematch','mobile']};
}
